"""Table 1, compact layout (2026-11-04 results markup): one block, total cost and multiple.

    uv run --offline python paper/table1_results.py [--out PATH]

Same numbers as paper/results_tables.py (it imports that script's helpers and reads the same
results/full/eval/summary.json, expanded labels); only the layout differs:
  - one block: S0, S1, S2@50, S4@50, then S3, S5, S6 (S4@50 is not repeated); the binary
    S2b@50 (data key S2@50) is left out, as Table 3 (ablations) carries the binary contrasts;
  - cost as total input tokens per query (description stage + frame step, thousands, averaged
    over all 722 queries) and as a multiple of S4@50's total;
  - paper names after the 2026-11-04 rename (data key -> paper name: S2@50 -> S2b@50,
    S2g@50 -> S2@50, S3g -> S3).
paper/results_tables.py is unchanged and still writes table1_strict.tex / table1_subsets.tex.
Writes results/paper/tables/table1.tex (and a copy in results/full/figures/table1_compact.tex).
No API calls.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
spec = importlib.util.spec_from_file_location("_t1tab", HERE / "results_tables.py")
T = importlib.util.module_from_spec(spec)
spec.loader.exec_module(T)

PAPER_OUT = ROOT / "results/paper/tables/table1.tex"
LOCAL_OUT = T.ROOT / "results/full/figures/table1_compact.tex"
NAME = {"S2@50": "S2b@50", "S2g@50": "S2@50", "S3g": "S3"}
NOTE: dict[str, str] = {}
DESC_SYS = ["S0", "S1", "S2g@50", "S4@50"]  # S2@50 (paper S2b@50, binary) dropped 2026-11-04
FRAME_SYS = ["S3g", "S5"]

CAPTION = (
    "Quality and cost per query (expanded labels). nDCG@10 over all queries ($n=350$ nested, 372 "
    "near-miss) and at $k=4$; R@1 over all queries. \\#tok: input tokens per query (thousands), "
    "averaged over all 722 queries; for the frame systems the description rerank S4@50 (10.4k) "
    "plus the frame step. $\\times$S4: total over S4@50's total. Bold is "
    "best per block. S6 sends {share:.0f}\\% of queries to frames (S4@50 top-two margin $\\le 2$); its $k=4$ and R@1 "
    "cells are not computed. Strict labels: Table~\\ref{{tab:results-strict}}."
)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=PAPER_OUT)
    args = ap.parse_args()
    d = json.loads(T.SUMMARY.read_text())
    labels = "expanded"
    L = d["labels"][labels]
    costs = d["costs"]
    full = {s: L["means"][s] for s in T.SETS}
    frame = {T.WHOLE[s]: L["subset_means"][T.WHOLE[s]] for s in T.SETS}
    base_s4 = T.pooled(costs, "S4@50", "tokens_in")

    def total(system: str) -> float:
        if system in FRAME_SYS:
            return base_s4 + T.pooled(costs, system, "tokens_in")
        return T.pooled(costs, system, "tokens_in")

    blocks = []
    vals = [T.quality_row(full, s, {k: k for k in T.SETS}) for s in DESC_SYS]
    blocks.append((DESC_SYS, vals, [total(s) for s in DESC_SYS]))
    fvals = [T.quality_row(frame, s, T.WHOLE) for s in FRAME_SYS]
    names, ftot = list(FRAME_SYS), [total(s) for s in FRAME_SYS]
    thr = {s: T.get(d, "s6", "test", T.WHOLE[s], "dev_threshold", T.S6_TARGET) for s in T.SETS}
    pthr = T.get(d, "s6", "test", "all queries", "dev_threshold", T.S6_TARGET)
    names.append("S6")
    fvals.append([thr["natural"]["ndcg10"], None, thr["twin"]["ndcg10"], None, None, None])
    ftot.append(pthr["cost"])
    blocks.append((names, fvals, ftot))

    body = []
    for i, (sys_, v, tot) in enumerate(blocks):
        cells = [[T.f3(x) for x in row] for row in v]
        T.bold_best(cells, v, list(range(6)))
        if i:
            body.append("\\midrule")
        for s, c, t in zip(sys_, cells, tot):
            name = NAME.get(s, s)
            mult = "--" if s == "S0" else f"{t / base_s4:.1f}"
            body.append(" & ".join([name + NOTE.get(name, "")] + c + [f"{t / 1000:.1f}", mult]) + " \\\\")
    tex = f"""% Generated by paper/table1_results.py from results/full/eval/summary.json (expanded labels; test set: {d['sources']} sources).
% Same numbers as paper/results_tables.py; compact layout (one block, total input tokens). Do not edit by hand.
\\begin{{table}}[t]
\\centering
\\small
\\setlength{{\\tabcolsep}}{{2.4pt}}
\\begin{{tabular}}{{@{{}}lccccccrr@{{}}}}
\\toprule
 & \\multicolumn{{2}}{{c}}{{Nested}} & \\multicolumn{{2}}{{c}}{{Near-miss}} & \\multicolumn{{2}}{{c}}{{R@1}} & \\multicolumn{{2}}{{c}}{{Cost}} \\\\
\\cmidrule(lr){{2-3}}\\cmidrule(lr){{4-5}}\\cmidrule(lr){{6-7}}\\cmidrule(l){{8-9}}
System & all & $k{{=}}4$ & all & $k{{=}}4$ & Nest. & N-miss & \\#tok & $\\times$S4 \\\\
\\midrule
{chr(10).join(body)}
\\bottomrule
\\end{{tabular}}
\\caption{{{CAPTION.format(share=100 * pthr['share'])}}}
\\label{{tab:results}}
\\end{{table}}
"""
    for out in (args.out, LOCAL_OUT):
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(tex)
        print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
