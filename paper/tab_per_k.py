"""Appendix tables of paired differences: tables/per_k_length.tex (the index-only systems
against S0 by k, Vript length bin and corpus part) and tables/frames_by_k_length.tex (the frame
systems against S4@50 and each other by k and Vript length bin).

    uv run python paper/tab_per_k.py [--labels expanded|strict] [--out-dir DIR]

Reads results/full/eval/summary.json (every number comes from it; the paper's summary is the
test-set eval, `systems.py --stage eval --sources-file results/full/select/sources100.json`).
Until now these two tables were made by hand from results/full/report.md; this script writes
them in the same layout. No API calls. Safe to rerun after a new eval.

frames_by_k_length.tex: the frame systems on every query of each set ("all near-miss",
"all nested" in subset_paired; S3g in place of S3, which ran only on the frame subsets), then
the frozen subsets (contested near-miss queries, nested Vript sample) with the same columns.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUMMARY = ROOT / "results/full/eval/summary.json"
PAPER_TABLES = ROOT / "results/paper/tables"
LOCAL_TABLES = ROOT / "results/full/figures"

SETS = {"natural": "Nested set", "twin": "Near-miss set"}
BINS = [
    ("lt30s", "Vript $<$30\\,s"),
    ("30to60s", "Vript 30--60\\,s"),
    ("1to2min", "Vript 1--2\\,min"),
    ("2to4min", "Vript 2--4\\,min"),
]
PARTS = [
    ("shot2story", "Shot2Story"),
    ("carebench", "CaReBench"),
    ("vript_short", "Vript short"),
    ("vript_long", "Vript long"),
]
PER_K_PAIRS = [
    ("S1 - S0", "S1 $-$ S0"),
    ("S2@50 - S0", "S2 $-$ S0"),
    ("S4@50 - S0", "S4 $-$ S0"),
    ("S4@50 - S2@50", "S4 $-$ S2"),
]
FRAME_PAIRS = [
    ("S5 - S4@50", "S5 $-$ S4"),
    ("S3g - S4@50", "S3g $-$ S4"),
    ("S3g - S5", "S3g $-$ S5"),
]
FRAME_GROUPS = [  # subset_paired key, heading, with corpus-part rows
    ("all near-miss", "Near-miss set, all queries", True),
    ("all nested", "Nested set, all queries", True),
    ("twin-both", "Near-miss queries, source and HN video in the pool (contested)", False),
    ("nested sample", "Nested sample (Vript only)", False),
]


def tnum(v: float) -> str:
    """$+.123$ style (sign, no leading zero), as the hand-made tables."""
    s = f"{v:+.3f}".replace("+0.", "+.").replace("-0.", "-.")
    return f"${s}$"


def tci(c: dict | None) -> str:
    if not c:
        return "--"
    return f"{tnum(c['mean'])} \\,[{tnum(c['ci_low'])}, {tnum(c['ci_high'])}]"


def cell(paired: dict, pair: str, key: str, group: str) -> dict | None:
    return paired.get(pair, {}).get("ndcg@10", {}).get(key, {}).get(group)


def n_of(paired: dict, pairs: list, key: str, group: str) -> int | None:
    for pair, _ in pairs:
        c = cell(paired, pair, key, group)
        if c:
            return c["n"]
    return None


def rows_for(paired: dict, pairs: list, parts: bool) -> list[str]:
    """All, k = 1..4, the Vript bins and (optionally) the corpus parts, as table lines."""
    groups = [("None", "all", "All")] + [("k", str(k), f"$k={k}$") for k in (1, 2, 3, 4)]
    groups += [("length_bin", b, name) for b, name in BINS]
    if parts:
        groups += [("dataset", p, name) for p, name in PARTS]
    out = []
    last = None
    for key, g, name in groups:
        n = n_of(paired, pairs, key, g)
        if n is None:
            continue
        if last is not None and key != last:
            out.append("\\addlinespace[2pt]")
        last = key
        cells = " & ".join(tci(cell(paired, pair, key, g)) for pair, _ in pairs)
        out.append(f"{name} & {n} & {cells} \\\\")
    return out


def per_k_table(d: dict, labels: str) -> str:
    L = d["labels"][labels]
    blocks = []
    for name, heading in SETS.items():
        blocks.append(f"\\multicolumn{{6}}{{l}}{{\\emph{{{heading}}}}} \\\\")
        blocks += rows_for(L["paired"][name], PER_K_PAIRS, parts=True)
        blocks.append("\\midrule")
    blocks.pop()
    head = " & ".join(name for _, name in PER_K_PAIRS)
    body = "\n".join(blocks)
    src = f"test set: {d['sources']} sources" if d.get("sources") else "all sources"
    return f"""% Generated by paper/tab_per_k.py from results/full/eval/summary.json ({labels} labels, paired differences; {src}); do not edit by hand.
\\begin{{table*}}[t]
\\centering
\\small
\\setlength{{\\tabcolsep}}{{3pt}}
\\begin{{tabular}}{{lrcccc}}
\\toprule
Group & $n$ & {head} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\caption{{Paired differences in nDCG@10 ({labels} labels) for the systems that read only the index, by number of constraints $k$, Vript length bin and corpus part, with 95\\% cluster-bootstrap intervals. S2 and S4 rerank S0's top 50. $n$ is the number of queries.}}
\\label{{tab:perk}}
\\end{{table*}}
"""


def frames_table(d: dict, labels: str) -> str:
    L = d["labels"][labels]
    blocks = []
    for key, heading, parts in FRAME_GROUPS:
        if key not in L["subset_paired"]:
            print(f"warning: {key} missing from subset_paired, skipped", file=sys.stderr)
            continue
        blocks.append(f"\\multicolumn{{5}}{{l}}{{\\emph{{{heading}}}}} \\\\")
        blocks += rows_for(L["subset_paired"][key], FRAME_PAIRS, parts=parts)
        blocks.append("\\midrule")
    blocks.pop()
    head = " & ".join(name for _, name in FRAME_PAIRS)
    body = "\n".join(blocks)
    src = f"test set: {d['sources']} sources" if d.get("sources") else "all sources"
    return f"""% Generated by paper/tab_per_k.py from results/full/eval/summary.json ({labels} labels, paired differences; {src}); do not edit by hand.
\\begin{{table*}}[t]
\\centering
\\small
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{lrccc}}
\\toprule
Group & $n$ & {head} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\caption{{Paired differences in nDCG@10 ({labels} labels) for the frame systems, which rerank the top 10 of S4@50, by $k$, Vript length bin and corpus part, with 95\\% cluster-bootstrap intervals: S5 (whole-query score) and S3g (graded per-constraint verifier) on every query of each set, then on the frozen frame subsets (the contested near-miss queries and the nested Vript sample, where S3 also ran).}}
\\label{{tab:frames}}
\\end{{table*}}
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--summary", type=Path, default=SUMMARY)
    ap.add_argument("--labels", default=None, help="label set (default: summary's primary_labels)")
    ap.add_argument("--out-dir", type=Path, default=PAPER_TABLES)
    args = ap.parse_args()
    d = json.loads(args.summary.read_text())
    labels = args.labels or d["primary_labels"]
    suffix = "" if labels == d["primary_labels"] else f"_{labels}"
    for name, make in (("per_k_length", per_k_table), ("frames_by_k_length", frames_table)):
        tex = make(d, labels)
        for out in (args.out_dir / f"{name}{suffix}.tex", LOCAL_TABLES / f"{name}{suffix}.tex"):
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(tex)
            print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
