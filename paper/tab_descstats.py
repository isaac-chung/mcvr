"""Description statistics of the evaluated test sources (the paper's Table descstats): per corpus
part and length bin, mean (min--max) of words, sentences, output tokens and input frames of the
indexed describe_v4 descriptions, plus the whole-corpus figures the paragraph quotes. FREE: reads
data/mc/<dataset>/{videos.jsonl, descriptions_fps05.jsonl} and the sources file only.

    uv run python paper/tab_descstats.py --sources-file results/full/select/sources100.json \
        [--out results/full/todo_recompute/descstats] [--tables-dir results/paper/tables]

Rows: Shot2Story, CaReBench, Vript short (all bins each), Vript long by bin (30-60 s, 1-2 min,
2-4 min), All. Words = whitespace tokens; sentences = runs of . ! ? followed by a space or the
end (at least 1); output tokens = cost.tokens_out billed by the describer; frames = n_frames.
Writes <out>/{summary.json, report.md, descstats.tex} and, with --tables-dir, descstats.tex there.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.datasets.mc import DATASETS, LENGTH_BINS, length_bin, read_jsonl  # noqa: E402

DATA = Path("data/mc")
OUT = Path("results/full/todo_recompute/descstats")
PART = {
    "shot2story": "Shot2Story",
    "carebench": "CaReBench",
    "vript_short": "Vript short",
    "vript_long": "Vript long",
}
BIN_TEX = {"lt30s": "$<$30\\,s", "30to60s": "30--60\\,s", "1to2min": "1--2\\,min", "2to4min": "2--4\\,min"}
SENT = re.compile(r"[.!?]+(?=\s|$)")
FIELDS = ("words", "sentences", "tokens_out", "frames")


def n_sentences(text: str) -> int:
    return max(1, len(SENT.findall(text.strip())))


def load_corpus() -> tuple[dict, dict]:
    videos, descs = {}, {}
    for ds in DATASETS:
        for v in read_jsonl(DATA / ds / "videos.jsonl"):
            videos[f"{ds}/{v['video_id']}"] = v
        for d in read_jsonl(DATA / ds / "descriptions_fps05.jsonl"):
            descs[f"{ds}/{d['video_id']}"] = d
    return videos, descs


def stats_of(source: str, videos: dict, descs: dict) -> dict | None:
    d = descs.get(source)
    text = (d or {}).get("description", "").strip()
    if not text:
        return None
    return {
        "source": source,
        "dataset": source.split("/")[0],
        "length_bin": length_bin(videos[source]["duration_s"]),
        "words": len(text.split()),
        "sentences": n_sentences(text),
        "tokens_out": int(d["cost"]["tokens_out"]),
        "frames": int(d["n_frames"]),
    }


def cell(rows: list[dict]) -> dict:
    out = {"n": len(rows)}
    for f in FIELDS:
        v = np.array([r[f] for r in rows], float)
        out[f] = {"mean": float(v.mean()), "min": float(v.min()), "max": float(v.max())}
    return out


def table_rows(rows: list[dict]) -> list[tuple[str, dict]]:
    out = []
    for ds in ("shot2story", "carebench", "vript_short"):
        rs = [r for r in rows if r["dataset"] == ds]
        if rs:
            out.append((PART[ds], cell(rs)))
    for b in LENGTH_BINS:
        rs = [r for r in rows if r["dataset"] == "vript_long" and r["length_bin"] == b]
        if rs:
            out.append((f"Vript long {BIN_TEX[b]}", cell(rs)))
    out.append(("All", cell(rows)))
    return out


def fmt(c: dict, f: str) -> str:
    if f == "sentences":
        return f"{c[f]['mean']:.1f} ({c[f]['min']:.0f}--{c[f]['max']:.0f})"
    return f"{c[f]['mean']:.0f} ({c[f]['min']:.0f}--{c[f]['max']:.0f})"


def tex(trows: list[tuple[str, dict]], n: int, source: str) -> str:
    lines = [
        f"% Generated by paper/tab_descstats.py from {source} ({n} sources).",
        "\\begin{table}[t]",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\resizebox{\\columnwidth}{!}{%",
        "\\begin{tabular}{@{}lrcccc@{}}",
        "\\toprule",
        " & $n$ & Words & Sentences & Output tok. & Frames \\\\",
        "\\midrule",
    ]
    for label, c in trows:
        if label == "All":
            lines.append("\\midrule")
        lines.append(
            f"{label} & {c['n']} & " + " & ".join(fmt(c, f) for f in FIELDS) + " \\\\"
        )
    lines += [
        "\\bottomrule",
        "\\end{tabular}}",
        "\\caption{Index descriptions of the evaluated test sources: mean (min--max) per source.}",
        "\\label{tab:descstats}",
        "\\end{table}",
    ]
    return "\n".join(lines) + "\n"


def corpus_stats(videos: dict, descs: dict, keep: set) -> dict:
    rows = [s for s in (stats_of(v, videos, descs) for v in videos) if s]
    words = np.array([r["words"] for r in rows], float)
    empty = [v for v in videos if not descs.get(v, {}).get("description", "").strip()]
    return {
        "videos": len(videos),
        "non_empty": len(rows),
        "empty": len(empty),
        "empty_test_sources": sorted(set(empty) & keep),
        "words_mean": float(words.mean()),
        "words_median": float(np.median(words)),
        "words_min": float(words.min()),
        "words_max": float(words.max()),
        "tokens_out_mean": float(np.mean([r["tokens_out"] for r in rows])),
        "over_three_sentences": int(sum(r["sentences"] > 3 for r in rows)),
        "over_three_sentences_share": float(np.mean([r["sentences"] > 3 for r in rows])),
    }


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--sources-file", default="results/full/select/sources100.json")
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--tables-dir", help="also write descstats.tex there")
    args = ap.parse_args(argv)
    keep = set(json.loads(Path(args.sources_file).read_text())["sources"])
    videos, descs = load_corpus()
    rows = [s for s in (stats_of(v, videos, descs) for v in sorted(keep)) if s]
    trows = table_rows(rows)
    res = {
        "sources_file": args.sources_file,
        "sources": len(keep),
        "with_description": len(rows),
        "table": {label: c for label, c in trows},
        "corpus": corpus_stats(videos, descs, keep),
        "per_source": rows,
    }
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.json").write_text(json.dumps(res, indent=1))
    table = tex(trows, len(rows), args.sources_file)
    (out / "descstats.tex").write_text(table)
    c = res["corpus"]
    md = [
        "# Description statistics of the test sources",
        "",
        f"{len(rows)} of {len(keep)} sources of {args.sources_file} have a non-empty description.",
        "",
        "| part / bin | n | words | sentences | output tokens | frames |",
        "|---|---|---|---|---|---|",
        *(f"| {label} | {c_['n']} | " + " | ".join(fmt(c_, f) for f in FIELDS) + " |" for label, c_ in trows),
        "",
        f"Whole corpus: {c['non_empty']:,} non-empty descriptions of {c['videos']:,} videos; mean "
        f"{c['words_mean']:.1f} words (median {c['words_median']:.0f}, range {c['words_min']:.0f}--"
        f"{c['words_max']:.0f}), {c['tokens_out_mean']:.1f} output tokens; {c['over_three_sentences']} "
        f"({c['over_three_sentences_share']:.1%}) exceed three sentences; {c['empty']} empty "
        f"descriptions, {len(c['empty_test_sources'])} of them test sources.",
    ]
    (out / "report.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    if args.tables_dir:
        dst = Path(args.tables_dir).expanduser() / "descstats.tex"
        shutil.copy(out / "descstats.tex", dst)
        print(f"wrote {dst}")
    print(f"wrote {out}/summary.json, report.md, descstats.tex")


if __name__ == "__main__":
    main()
