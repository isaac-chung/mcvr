"""Sample one index description per length bin for the paper's appendix. Free: no API calls.

For each length bin (< 30 s, 30-60 s, 1-2 min, 2-4 min), draw one full-run test source (seed 1)
with a non-empty description and a nested query, and show its 0.5 fps describe_v4 description
next to the longest nested query built from it (the facts the description should carry).
Writes results/full/figures/desc_samples.json and the LaTeX table
results/paper/tables/desc_samples.tex.

    uv run python paper/tab_desc_samples.py
"""

from __future__ import annotations

import json
import random
from pathlib import Path

from src.datasets.mc import LENGTH_BINS, length_bin

ROOT = Path("data/mc")
SEED = 1
OUT_JSON = Path("results/full/figures/desc_samples.json")
OUT_TEX = Path("results/paper/tables/desc_samples.tex")
BIN_NAMES = {
    "lt30s": "$<$30 s",
    "30to60s": "30--60 s",
    "1to2min": "1--2 min",
    "2to4min": "2--4 min",
}


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def tex(text: str) -> str:
    for a, b in (
        ("\\", "\\textbackslash{}"),
        ("&", "\\&"),
        ("%", "\\%"),
        ("$", "\\$"),
        ("#", "\\#"),
        ("_", "\\_"),
        ("{", "\\{"),
        ("}", "\\}"),
        ("~", "\\~{}"),
        ("^", "\\^{}"),
        ('"', "''"),
    ):
        text = text.replace(a, b)
    return text


def main() -> None:
    sources = json.loads((ROOT / "full" / "sample.json").read_text())["query_sources"]
    queries: dict[str, list[dict]] = {}
    for q in read_jsonl(ROOT / "full" / "queries.jsonl"):
        queries.setdefault(q["source"], []).append(q)
    videos, descriptions = {}, {}
    for ds in sorted({s.split("/")[0] for s in sources}):
        for v in read_jsonl(ROOT / ds / "videos.jsonl"):
            videos[f"{ds}/{v['video_id']}"] = v
        for d in read_jsonl(ROOT / ds / "descriptions_fps05.jsonl"):
            descriptions[f"{ds}/{d['video_id']}"] = d

    rng = random.Random(SEED)
    rows = []
    for b in LENGTH_BINS:
        pool = sorted(
            s
            for s in sources
            if length_bin(videos[s]["duration_s"]) == b
            and descriptions.get(s, {}).get("description", "").strip()
            and queries.get(s)
        )
        pick = rng.choice(pool)
        q = max(queries[pick], key=lambda r: r["k"])
        d = descriptions[pick]
        rows.append(
            {
                "bin": b,
                "source": pick,
                "duration_s": round(videos[pick]["duration_s"], 1),
                "n_frames": d["n_frames"],
                "description": d["description"].strip(),
                "query_id": q["query_id"],
                "k": q["k"],
                "query": q["query"],
                "facts": [
                    {"text": f["text"], "type": f["type"], "index_visible": f.get("index_visible")}
                    for f in q["facts"]
                ],
                "pool_size": len(pool),
            }
        )

    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(rows, indent=1) + "\n")

    lines = [
        "% Generated by paper/tab_desc_samples.py (seed 1); do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering\\small",
        "\\begin{tabular}{@{}p{0.11\\textwidth}p{0.50\\textwidth}p{0.33\\textwidth}@{}}",
        "\\toprule",
        (
            "Source & Index description (describe\\_v4, 0.5 fps) & Longest nested query built from "
            "the source \\\\"
        ),
        "\\midrule",
    ]
    for r in rows:
        ds = r["source"].split("/")[0].replace("_", " ")
        head = f"{BIN_NAMES[r['bin']]}\\newline {ds}\\newline {r['duration_s']:.0f} s, {r['n_frames']} frames"
        lines.append(f"{head} & {tex(r['description'])} & ($k={r['k']}$) {tex(r['query'])} \\\\")
        lines.append("\\addlinespace")
    lines[-1] = "\\bottomrule"
    lines += [
        "\\end{tabular}",
        (
            "\\caption{One randomly drawn test source per length bin (seed 1): its index description "
            "and the longest nested query built from its caption. The description is all that S0, "
            "S2 and S4 see of the video.}"
        ),
        "\\label{tab:desc_samples}",
        "\\end{table*}",
    ]
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TEX.write_text("\n".join(lines) + "\n")
    for r in rows:
        print(f"{r['bin']:8s} {r['source']}  {r['duration_s']} s  k={r['k']}")
    print(f"wrote {OUT_JSON} and {OUT_TEX}")


if __name__ == "__main__":
    main()
