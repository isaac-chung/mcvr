"""Fact-type distribution through the fact-mining funnel (appendix "Query Construction and Labels").

    python paper/tab_fact_funnel.py [--sources-file results/full/select/sources100.json]

Reads data/mc/full/constraints.jsonl (every test source, or with --sources-file the drawn
sources of the study's test set; the verified totals are checked only without it) and counts
facts per mined type at each
stage: mined; selectable (the fixed type and flag rule in src/constraints.py); grounded
(natural candidates sent to both VLMs); kept (both VLMs answer yes); dropped (not confirmed by
both). Reconciles to the verified totals and prints any mismatch. Writes
results/full/figures/fact_funnel.json and tables/fact_funnel.tex (copied into results/paper/ when
that folder exists). The share of kept facts in the final queries is not derived: nested queries
use a type-capped subset and j-condition queries use shared facts mined from caption pairs, not
these candidates. No API calls.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "results/paper"
OUT = ROOT / "results/full/figures"
ORDER = [  # data label, paper name
    ("attribute", "Attribute"),
    ("object", "Object"),
    ("on_screen_text", "On-screen text"),
    ("count", "Count"),
    ("scene", "Scene"),
    ("action", "Action"),
    ("spatial_relation", "Spatial relation"),
    ("temporal_order", "Temporal order"),
    ("other", "Other"),
]
EXPECT = {
    "mined": 10104,
    "selectable": 5686,
    "grounded": 2327,
    "kept": 1499,
    "dropped": 828,
    "both_no": 288,
    "g_no_a_yes": 164,
    "g_yes_a_no": 182,
    "other_combo": 194,
    "type_removed": 4393,
    "sources": 280,
}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sources-file", help="keep only these sources ({'sources': [...]})")
    args = ap.parse_args()
    rows = [json.loads(l) for l in (ROOT / "data/mc/full/constraints.jsonl").open()]
    if args.sources_file:
        keep = set(json.loads(Path(args.sources_file).read_text())["sources"])
        rows = [r for r in rows if r["source"] in keep]
    st = {s: Counter() for s in ("mined", "selectable", "grounded", "kept")}
    combos = Counter()
    for r in rows:
        ftype = {f["id"]: f["type"] for f in r["facts"]}
        for f in r["facts"]:
            st["mined"][f["type"]] += 1
            st["selectable"][f["type"]] += bool(f["selectable"])
        for g in r["grounding"]:
            if g["role"] != "natural":
                continue
            ans = {m.split(":")[0]: v["answer"] for m, v in g["answers"].items()}
            st["grounded"][ftype[int(g["key"][1:])]] += 1
            combos[(ans["gemini"], ans["openai"])] += 1
        for i in r["grounded"]:
            st["kept"][ftype[i]] += 1
    unknown = set(st["mined"]) - {t for t, _ in ORDER}
    assert not unknown, unknown
    tot = {s: sum(c.values()) for s, c in st.items()}
    tot["dropped"] = tot["grounded"] - tot["kept"]
    got = {
        **tot,
        "both_no": combos[("no", "no")],
        "g_no_a_yes": combos[("no", "yes")],
        "g_yes_a_no": combos[("yes", "no")],
        "sources": len(rows),
        "type_removed": sum(
            st["mined"][t] for t in ("action", "spatial_relation", "temporal_order", "other")
        ),
    }
    got["other_combo"] = got["dropped"] - got["both_no"] - got["g_no_a_yes"] - got["g_yes_a_no"]
    bad = {k: (got[k], v) for k, v in EXPECT.items() if got[k] != v}
    print("totals", got)
    if args.sources_file:
        print(f"restricted to {len(rows)} sources of {args.sources_file}; no reconciliation")
    else:
        print("MISMATCH (got, expected):" if bad else "reconciles to verified totals", bad or "")
    print(
        "type pass without flags:",
        sum(st["mined"][t] for t, _ in ORDER[:5]),
        "vs selectable",
        tot["selectable"],
    )
    print(
        "not-yes combos:",
        {f"{a}/{b}": v for (a, b), v in combos.items() if (a, b) != ("yes", "yes")},
    )

    def line(name, c):
        g, k = c["grounded"], c["kept"]
        if g == 0:
            return f"{name} & {c['mined']:,} & {c['selectable']:,} & -- & -- & -- & -- \\\\"
        d = g - k
        return (
            f"{name} & {c['mined']:,} & {c['selectable']:,} & {g:,} & {k:,} & {d:,} & "
            f"{d / g:.3f}".replace("0.", ".")
            + " \\\\"
        )

    body = [line(n, {s: st[s][t] for s in st}) for t, n in ORDER]
    n5 = 5
    header = "% Generated by paper/tab_fact_funnel.py from data/mc/full/constraints.jsonl" + (
        f" ({len(rows)} sources of {args.sources_file}).\n" if args.sources_file else ".\n"
    )
    tex = (
        header + "\\begin{table}[t]\n\\centering\n\\small\n\\setlength{\\tabcolsep}{2pt}\n"
        "\\begin{tabular}{@{}lrrrrrr@{}}\n\\toprule\n"
        "Type & Mined & Select. & Grounded & Kept & Dropped & Rate \\\\\n\\midrule\n"
        + "\n".join(body[:n5])
        + "\n\\midrule\n"
        + "\n".join(body[n5:])
        + "\n\\midrule\n"
        + line("All", {s: tot[s] for s in tot})
        + "\n\\bottomrule\n\\end{tabular}\n"
        f"\\caption{{Mined facts by type through the fact-mining funnel, for the {len(rows)} test sources. "
        "\\emph{Mined}: facts listed by the LLM, labelled with its own type. \\emph{Selectable}: "
        "facts that pass the fixed rule (type attribute, object, on-screen text, count or scene, "
        "visible in a single frame, self-contained); the other types are removed by the rule and never reach the VLMs. "
        "\\emph{Grounded}: selectable facts chosen as candidates and checked by both VLMs "
        "(distinctive facts first, with a cap per source). \\emph{Kept}: both VLMs answer yes. "
        "\\emph{Dropped}: not confirmed by both VLMs (a no or unsure from either); drop rate is "
        "dropped over grounded.}\n"
        "\\label{tab:fact-funnel}\n\\end{table}\n"
    )
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "fact_funnel.json").write_text(
        json.dumps({"stages": {s: dict(c) for s, c in st.items()}, "totals": got}, indent=1)
    )
    (OUT / "fact_funnel.tex").write_text(tex)
    (PAPER / "tables").mkdir(parents=True, exist_ok=True)
    (PAPER / "tables/fact_funnel.tex").write_text(tex)
    print("copied into", PAPER)


if __name__ == "__main__":
    main()
