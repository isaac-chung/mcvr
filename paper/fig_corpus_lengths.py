"""Corpus length distribution for the paper's appendix (Appendix B, "Corpus").

    python paper/fig_corpus_lengths.py     (matplotlib needed for the figure)

Reads data/mc/<part>/videos.jsonl for the four corpus parts, bins durations with the study's
rule (src/datasets/mc.py: <30 s, 30-60 s, 1-2 min, 2-4 min), and writes
results/full/figures/corpus_lengths.json, the stacked-bar figure fig_corpus_lengths.pdf and the
LaTeX table tables/corpus_lengths.tex (copied into results/paper/).
No API calls.
"""

from __future__ import annotations

import json
import statistics as st
from collections import Counter
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT / "results/paper"
OUT = ROOT / "results/full/figures"
PARTS = [
    ("shot2story", "Shot2Story", "#2a78d6"),
    ("carebench", "CaReBench", "#eb6834"),
    ("vript_short", "Vript short", "#199e70"),
    ("vript_long", "Vript long", "#5b3fa8"),
]
BINS = ["lt30s", "30to60s", "1to2min", "2to4min"]
BIN_LABELS = ["under 30 s", "30--60 s", "1--2 min", "2--4 min"]
BIN_TICKS = ["<30 s", "30\u201360 s", "1\u20132 min", "2\u20134 min"]
INK, INK_2, GRID = "#0b0b0b", "#52514e", "#d9d8d4"


def length_bin(d: float) -> str:  # same rule as src.datasets.mc.length_bin
    if d < 30:
        return "lt30s"
    if d <= 60:
        return "30to60s"
    if d <= 120:
        return "1to2min"
    if d <= 240.0:
        return "2to4min"
    raise ValueError(d)


def main() -> None:
    res = {}
    for key, name, _ in PARTS:
        rows = [json.loads(l) for l in (ROOT / f"data/mc/{key}/videos.jsonl").open()]
        d = sorted(r["duration_s"] for r in rows)
        c = Counter(length_bin(x) for x in d)
        res[key] = {
            "name": name,
            "n": len(d),
            "bins": {b: c.get(b, 0) for b in BINS},
            "min": d[0],
            "median": st.median(d),
            "max": d[-1],
            "p10": d[int(0.1 * len(d))],
            "p90": d[int(0.9 * len(d))],
        }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "corpus_lengths.json").write_text(json.dumps(res, indent=1))
    total = sum(v["n"] for v in res.values())
    print("total videos", total)

    plt.rcParams.update({
        "font.family": "serif",
        "font.serif": ["Times", "Times New Roman", "STIX Two Text", "STIXGeneral", "DejaVu Serif"],
        "mathtext.fontset": "stix", "pdf.fonttype": 42,
    })
    fig, ax = plt.subplots(figsize=(3.3, 2.1))
    bottoms = [0] * len(BINS)
    for key, name, color in PARTS:
        vals = [res[key]["bins"][b] for b in BINS]
        ax.bar(range(len(BINS)), vals, bottom=bottoms, color=color, width=0.62, label=name,
               edgecolor="white", linewidth=0.4, zorder=3)
        bottoms = [a + b for a, b in zip(bottoms, vals)]
    for i, tot in enumerate(bottoms):
        ax.text(i, tot + max(bottoms) * 0.015, f"{tot:,}", ha="center", va="bottom", fontsize=6.5, color=INK)
    ax.set_xticks(range(len(BINS)))
    ax.set_xticklabels(BIN_TICKS, fontsize=6.5, color=INK)
    ax.set_ylabel("videos", fontsize=7, color=INK)
    ax.set_ylim(0, max(bottoms) * 1.12)
    ax.tick_params(colors=INK_2, labelcolor=INK, labelsize=6.5, width=0.6, length=2.5)
    ax.grid(axis="y", color=GRID, lw=0.5, zorder=0)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(INK_2)
        ax.spines[s].set_linewidth(0.6)
    ax.legend(frameon=False, fontsize=6.3, loc="upper right", handlelength=1.0, labelspacing=0.3)
    fig.subplots_adjust(left=0.17, right=0.99, top=0.97, bottom=0.12)
    pdf = OUT / "fig_corpus_lengths.pdf"
    fig.savefig(pdf)
    fig.savefig(OUT / "fig_corpus_lengths.png", dpi=300)
    print("wrote", pdf)

    def sec(x: float) -> str:
        return f"{x:.0f}" if x >= 100 else f"{x:.1f}"

    rows = []
    for key, name, _ in PARTS:
        v = res[key]
        rows.append(
            f"{name} & {v['n']:,} & "
            + " & ".join(f"{v['bins'][b]:,}" for b in BINS)
            + f" & {sec(v['min'])} & {sec(v['median'])} & {sec(v['max'])} \\\\"
        )
    tex = (
        "% Generated by paper/fig_corpus_lengths.py from data/mc/<part>/videos.jsonl.\n"
        "\\begin{table}[t]\n\\centering\n\\small\n\\setlength{\\tabcolsep}{3pt}\n"
        "\\resizebox{\\columnwidth}{!}{%\n\\begin{tabular}{@{}lrrrrr@{\\hspace{9pt}}rrr@{}}\n\\toprule\n"
        " & & \\multicolumn{4}{c}{Videos by length} & \\multicolumn{3}{c}{Duration (s)} \\\\\n"
        "\\cmidrule(lr){3-6}\\cmidrule(l){7-9}\n"
        "Part & Videos & $<$30\\,s & 30--60\\,s & 1--2\\,min & 2--4\\,min & Min & Median & Max \\\\\n\\midrule\n"
        + "\n".join(rows)
        + f"\n\\midrule\nAll & {total:,} & "
        + " & ".join(f"{sum(res[k]['bins'][b] for k, _, _ in PARTS):,}" for b in BINS)
        + " & & & \\\\\n\\bottomrule\n\\end{tabular}}\n"
        "\\caption{The 8,603 corpus videos by part and length bin, with duration in seconds. Bins use the study's rule: under 30\\,s, up to 60\\,s, up to 120\\,s and up to 240\\,s.}\n"
        "\\label{tab:corpus-lengths}\n\\end{table}\n"
    )
    (OUT / "corpus_lengths.tex").write_text(tex)
    (PAPER / "figures").mkdir(parents=True, exist_ok=True)
    (PAPER / "tables").mkdir(parents=True, exist_ok=True)
    (PAPER / "figures/fig_corpus_lengths.pdf").write_bytes(pdf.read_bytes())
    (PAPER / "tables/corpus_lengths.tex").write_text(tex)
    print("copied into", PAPER)


if __name__ == "__main__":
    main()
